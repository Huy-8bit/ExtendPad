import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case system, en, vi
    var id: String { rawValue }
    var resolved: String {
        switch self {
        case .en: return "en"
        case .vi: return "vi"
        case .system:
            return Locale.preferredLanguages.first?.hasPrefix("vi") == true ? "vi" : "en"
        }
    }
}

